import json
from pathlib import Path

from app.data.historical_layers import DEMO_BBOX, get_map_url, historical_layers, source

ROOT = Path(__file__).resolve().parents[2]


def test_get_map_url_uses_crs84_and_the_demo_bbox():
    url = get_map_url("RASTER_ORTOFOTO_1945")
    assert "CRS=CRS:84" in url
    assert "LAYERS=RASTER_ORTOFOTO_1945" in url
    min_lon, min_lat, max_lon, max_lat = DEMO_BBOX
    assert f"BBOX={min_lon},{min_lat},{max_lon},{max_lat}" in url


def test_historical_layers_cover_1935_1939_1945():
    layers = historical_layers()
    years = {layer["year"] for layer in layers}
    assert years == {1935, 1939, 1945}
    for layer in layers:
        assert layer["source_id"] == "warsaw-historical-wms"
        assert layer["bounds"] == [[20.95, 52.19], [21.08, 52.28]]
        assert layer["image_url"].startswith("https://wms.um.warszawa.pl/serwis?")


def test_source_is_labelled_real_with_attribution():
    s = source()
    assert s["mode"] == "real"
    assert "Warszawy" in s["attribution"]
    assert "GetFeatureInfo" in s["method"]  # honest about the render-only limitation


def test_committed_fixture_matches_the_live_generator():
    """The fixture is regenerated by running the module live (verifying each
    image actually renders); this just checks its shape stays consistent
    with what the generator currently produces, not a live network call."""
    fixture = json.loads((ROOT / "data/fixtures/historical-layers.json").read_text(encoding="utf-8"))
    assert {layer["id"] for layer in fixture["layers"]} == {"warsaw_1935", "warsaw_1939", "warsaw_1945"}
    assert fixture["sources"][0]["id"] == "warsaw-historical-wms"
